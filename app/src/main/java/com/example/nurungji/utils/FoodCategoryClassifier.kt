package com.example.nurungji.utils

fun classifyFoodCategory(itemName: String): String {
    val normalized = itemName
        .lowercase()
        .replace(" ", "")
        .replace("-", "")
        .replace("_", "")

    if (normalized.isBlank()) return "기타"

    val categoryKeywords = listOf(
        "냉동식품" to listOf(
            "냉동", "만두", "피자", "핫도그", "돈까스", "돈가스", "너겟", "치킨너겟",
            "볶음밥", "떡갈비", "군만두", "감자튀김", "냉동밥", "냉동면"
        ),
        "유제품" to listOf(
            "우유", "치즈", "요거트", "요구르트", "요플레", "버터", "크림", "생크림",
            "두유", "그릭요거트", "모짜렐라", "모차렐라", "체다", "아이스크림"
        ),
        "육류" to listOf(
            "소고기", "쇠고기", "돼지고기", "삼겹살", "목살", "앞다리", "뒷다리",
            "갈비", "스테이크", "닭", "닭고기", "닭가슴살", "오리", "양고기",
            "한우", "돈육", "우육", "계육", "햄", "소시지", "소세지", "베이컨"
        ),
        "채소" to listOf(
            "상추", "양상추", "깻잎", "시금치", "배추", "양배추", "대파", "쪽파",
            "파", "양파", "마늘", "생강", "당근", "오이", "호박", "애호박",
            "가지", "버섯", "팽이버섯", "새송이", "표고", "브로콜리", "파프리카",
            "피망", "고추", "감자", "고구마", "무", "콩나물", "숙주", "청경채",
            "샐러드", "토마토"
        ),
        "과일" to listOf(
            "사과", "배", "귤", "감귤", "오렌지", "레몬", "라임", "바나나",
            "딸기", "포도", "샤인머스캣", "블루베리", "라즈베리", "복숭아",
            "자두", "수박", "참외", "멜론", "키위", "망고", "파인애플",
            "체리", "감", "홍시", "아보카도"
        ),
        "음료" to listOf(
            "물", "생수", "탄산수", "주스", "쥬스", "콜라", "사이다", "환타",
            "커피", "라떼", "아메리카노", "차", "녹차", "홍차", "보리차",
            "음료", "음료수", "에이드", "스무디", "맥주", "소주", "막걸리",
            "와인", "이온음료", "스포츠음료"
        )
    )

    return categoryKeywords.firstOrNull { (_, keywords) ->
        keywords.any { keyword -> normalized.contains(keyword) }
    }?.first ?: "기타"
}
